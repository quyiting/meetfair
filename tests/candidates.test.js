const assert = require('assert')
const { getRoomCandidates } = require('../miniprogram/utils/candidates')
const automatic = Array.from({ length: 100 }, (_, i) => ({ id: `v${i}` }))
const manual = Array.from({ length: 8 }, (_, i) => ({ id: `m${i}` }))
const all = getRoomCandidates({ venues: automatic, nominatedVenues: manual.concat(manual[0]) })
assert.strictEqual(all.length, 100)
assert.deepStrictEqual(all.slice(0, 8), manual)
assert.deepStrictEqual(getRoomCandidates({ venues: automatic }), automatic)
console.log('candidates tests: ok')
