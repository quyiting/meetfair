const assert = require('assert')
const cloudRoom = require('./helpers/room-cloud')
const venue = { id: 'v', name: '测试地点', category: 'food', latitude: 31, longitude: 121, address: '测试路' }
async function run() {
  const h = cloudRoom({ id: 'test', meetingDate: '2099-10-20', meetingTime: '18:30',
    candidateDates: ['2099-10-20', '2099-10-21'], members: [{ id: 'self' }, { id: 'friend' }], venues: [venue] })
  assert(!(await h.call('setAttendance', { status: 'yes', planRevision: 0 })).ok)
  assert((await h.call('setMeetingTime', { time: '19:00' })).ok)
  assert.strictEqual(h.doc.room.planRevision, 1)
  assert((await h.call('setFinalVenue', { venueId: 'v' })).ok)
  assert.strictEqual(h.doc.room.planRevision, 2)
  assert((await h.call('setAttendance', { status: 'yes', planRevision: 2, memberId: 'friend' })).ok)
  assert.strictEqual(h.doc.room.attendanceResponses[0].memberId, 'self')
  assert((await h.call('setMeetingTime', { time: '19:00' })).ok)
  assert.strictEqual(h.doc.room.planRevision, 2, '重复确认同一时间不清除意向')
  assert((await h.call('setFinalVenue', { venueId: 'v' })).ok)
  assert.strictEqual(h.doc.room.attendanceResponses.length, 1)
  h.as('guest')
  assert((await h.call('setAttendance', { status: 'maybe', planRevision: 2 })).ok)
  assert.strictEqual(h.doc.room.attendanceResponses.length, 2)
  assert(!(await h.call('setAttendance', { status: 'bad', planRevision: 2 })).ok)
  h.as('stranger')
  assert(!(await h.call('setAttendance', { status: 'yes', planRevision: 2 })).ok)
  h.as('owner')
  assert((await h.call('setMeetingTime', { time: '19:00', date: '2099-10-21' })).ok)
  assert.strictEqual(h.doc.room.planRevision, 3)
  assert.deepStrictEqual(h.doc.room.attendanceResponses, [])
  assert(!(await h.call('setAttendance', { status: 'yes', planRevision: 2 })).ok)
  const [changed, late] = await Promise.all([
    h.call('setMeetingTime', { time: '20:00' }), h.call('setAttendance', { status: 'yes', planRevision: 3 })
  ])
  assert(changed.ok)
  assert.strictEqual(late.ok, false)
  assert.strictEqual(h.doc.room.planRevision, 4)
  assert.deepStrictEqual(h.doc.room.attendanceResponses, [])
  console.log('attendance tests: ok')
}
run().catch((e) => { console.error(e); process.exitCode = 1 })
